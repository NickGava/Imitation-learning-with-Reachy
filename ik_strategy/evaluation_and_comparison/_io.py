'''
_io.py
=============================================================================
I/O for the evaluation_and_comparison module - read/write CSV only.

BC trajectories are generated by bc_approach/*/test_bc.py and saved
as bc_trajectory.csv before running the evaluation.

Public functions:
    load_baseline(dataset_dir)                   → np.ndarray | None
    load_canonical(split_dir)                    → np.ndarray | None  (standard DBA)
    load_canonical_shape(split_dir)              → np.ndarray | None  (ShapeDBA)
    load_bc_trajectory(split_dir, arch)          → np.ndarray | None  (mean if multi-run)
    load_bc_runs_variance(split_dir, arch)       → dict[str,float] | None
    start_pose_from_canonical(canonical)         → np.ndarray
    save_results_csv(results, output_dir)
'''

from pathlib import Path
from typing import Dict, List, Optional

import numpy as np
import pandas as pd

from utilities.config import JOINT_COLS
from evaluation_and_comparison._config import N_JOINTS


# ============================================================================
# Helpers
# ============================================================================

def _load_joint_csv(path: Path, label: str = '') -> Optional[np.ndarray]:
    '''
    Load a CSV with columns JOINT_COLS and return an array (T, 16).
    Pad with zeros if some columns are missing.
    '''
    if not path.exists():
        if label:
            print(f'  [!] {label}: {path.name} non trovato')
        return None
    df   = pd.read_csv(path)
    cols = [c for c in JOINT_COLS if c in df.columns]
    arr  = df[cols].dropna().values.astype(float)
    if len(cols) < N_JOINTS:
        padded = np.zeros((len(arr), N_JOINTS))
        for i, c in enumerate(cols):
            padded[:, JOINT_COLS.index(c)] = arr[:, i]
        arr = padded
    if label:
        print(f'  {label}: {len(arr)} frame')
    return arr


# ============================================================================
# Loading trajectories
# ============================================================================

def load_baseline(dataset_dir: Path) -> Optional[np.ndarray]:
    return _load_joint_csv(dataset_dir / 'baseline.csv', 'Baseline')


def load_canonical(split_dir: Path) -> Optional[np.ndarray]:
    '''Loads canonical.csv (DBA standard) from the split folder.'''
    return _load_joint_csv(split_dir / 'canonical.csv', 'Canonical')


def load_canonical_shape(split_dir: Path) -> Optional[np.ndarray]:
    '''Loads canonicalShape.csv (ShapeDBA) from the split folder.'''
    return _load_joint_csv(split_dir / 'canonicalShape.csv', 'CanonicalShape')


def load_bc_trajectory(split_dir: Path, arch: str) -> Optional[np.ndarray]:
    '''
    Loads the BC trajectory for a given architecture.
    Prefers bc_trajectory_mean.csv (multi-run) if available,
    otherwise falls back to bc_trajectory.csv (single-run / backward compat).
    '''
    mean_path = split_dir / arch / 'bc_trajectory_mean.csv'
    if mean_path.exists():
        return _load_joint_csv(mean_path, label=f'{arch} (mean runs)')
    path = split_dir / arch / 'bc_trajectory.csv'
    return _load_joint_csv(path, label=arch)


def load_bc_runs_variance(split_dir: Path, arch: str) -> Optional[Dict[str, float]]:
    '''
    Reads runs_metrics.csv and returns the std for each scalar metric.
    Returns None if the file does not exist (single-run mode).
    '''
    path = split_dir / arch / 'runs_metrics.csv'
    if not path.exists():
        return None
    df = pd.read_csv(path)
    if df.shape[0] < 2:
        return None   # need at least 2 runs to have a significant std
    scalar_cols = [c for c in df.columns if c != 'run']
    return {col: float(df[col].std())
            for col in scalar_cols
            if not df[col].isna().all()}


def load_human_demos(landmarks_root: Path,
                      exercise_num: int,
                      n_demos: int = 55) -> List[np.ndarray]:
    '''
    Loads the joint_ik.csv files for human demonstrations for a given exercise.
    Used as reference for the bounds of the metrics (not shown in the plots).

    n_demos : 10 -> 2 subjects, 25 -> 5, 55 -> all 11
    '''
    from utilities.split_utils import select_subjects

    exercise_name = f'exercise_{exercise_num:03d}'
    all_subj_dirs = sorted(landmarks_root.glob('subject_*'))
    selected      = select_subjects(all_subj_dirs, n_demos)
    selected_set  = {d.name for d in selected}

    demos = []
    for subj_dir in sorted(landmarks_root.glob('subject_*')):
        if subj_dir.name not in selected_set:
            continue
        exer_dir = subj_dir / exercise_name
        if not exer_dir.is_dir():
            continue
        for video_dir in sorted(exer_dir.glob('video_*')):
            arr = _load_joint_csv(video_dir / 'joint_ik.csv')
            if arr is not None and len(arr) >= 2:
                demos.append(arr)
    print(f'  Human demos loaded: {len(demos)} '
          f'({len(selected)} subjects, split n_{n_demos:02d})')
    return demos


def start_pose_from_canonical(canonical: Optional[np.ndarray]) -> np.ndarray:
    '''First frame of the canonical trajectory as start pose, or array of zeros if absent.'''
    if canonical is not None and len(canonical) > 0:
        return canonical[0].copy().astype(np.float32)
    return np.zeros(N_JOINTS, dtype=np.float32)


